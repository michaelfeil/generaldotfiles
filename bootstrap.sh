#!/usr/bin/env bash
set -euo pipefail

usage() {
  echo "Usage: bash bootstrap.sh [--skip-install] [--skip-tpm]"
  echo "Install development tools and link dotfiles into HOME."
}

skip_tpm=false
skip_install=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --skip-tpm) skip_tpm=true ;;
    --skip-install) skip_install=true ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
  shift
done

repo_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
dotdir="$HOME/.me"
backup_dir=""

backup() {
  local target="$1"
  if [[ -z "$backup_dir" ]]; then
    backup_dir="$(mktemp -d "$HOME/.dotfiles-backup.XXXXXXXX")"
    printf 'Saving existing files in %s\n' "$backup_dir"
  fi
  mv -- "$target" "$backup_dir/$(basename -- "$target")"
}

link_file() {
  local source="$1" target="$2"
  if [[ -L "$target" && "$(readlink -- "$target")" == "$source" ]]; then
    return
  fi
  if [[ -e "$target" || -L "$target" ]]; then
    backup "$target"
  fi
  ln -s -- "$source" "$target"
}

# Older bootstraps linked .gitconfig to a file inside .me. Detach it first.
if [[ -e "$HOME/.gitconfig" ]]; then
  git config --file "$HOME/.gitconfig" --list >/dev/null
fi
if [[ -L "$HOME/.gitconfig" ]]; then
  gitconfig_copy="$(mktemp "$HOME/.gitconfig.XXXXXXXX")"
  if [[ -e "$HOME/.gitconfig" ]]; then
    cp -- "$HOME/.gitconfig" "$gitconfig_copy"
  fi
  backup "$HOME/.gitconfig"
  mv -- "$gitconfig_copy" "$HOME/.gitconfig"
fi

# Support running directly from a checkout already located at ~/.me.
if [[ ! -d "$dotdir" ]] || [[ "$repo_dir" != "$(cd -- "$dotdir" && pwd -P)" ]]; then
  link_file "$repo_dir" "$dotdir"
fi

loader="$(mktemp "$HOME/.my_bashrc.XXXXXXXX")"
printf '%s\n' '# Generated by generaldotfiles/bootstrap.sh.' > "$loader"
printf '%s\n' '[[ $- == *i* ]] || return 0' >> "$loader"
for file in "$dotdir"/into_bashrc/*; do
  [[ -f "$file" ]] || continue
  printf 'source %q\n' "$file" >> "$loader"
done
if [[ -f "$HOME/.my_bashrc" ]] && cmp -s "$loader" "$HOME/.my_bashrc"; then
  rm -- "$loader"
else
  if [[ -e "$HOME/.my_bashrc" || -L "$HOME/.my_bashrc" ]]; then
    backup "$HOME/.my_bashrc"
  fi
  mv -- "$loader" "$HOME/.my_bashrc"
fi

source_line='source ~/.my_bashrc'
if ! grep -qxF "$source_line" "$HOME/.bashrc" 2>/dev/null; then
  printf '\n%s\n' "$source_line" >> "$HOME/.bashrc"
fi

link_file "$dotdir/vimrc" "$HOME/.vimrc"
link_file "$dotdir/tmux.conf" "$HOME/.tmux.conf"
link_file "$dotdir/tmux-completion.bash" "$HOME/.tmux-completion.bash"

# Keep identity and machine-specific settings in the user's file.
if ! git config --file "$HOME/.gitconfig" --get-all include.path 2>/dev/null |
    grep -qxF "$dotdir/gitconfig"; then
  git config --file "$HOME/.gitconfig" --add include.path "$dotdir/gitconfig"
fi

if [[ "$skip_install" == false ]]; then
  bash "$repo_dir/install.sh"
fi

if [[ "$skip_tpm" == false && ! -e "$HOME/.tmux/plugins/tpm" ]]; then
  mkdir -p "$HOME/.tmux/plugins"
  git clone https://github.com/tmux-plugins/tpm "$HOME/.tmux/plugins/tpm"
fi

echo 'Dotfiles installed. Run: source ~/.bashrc'
